class Command(BaseCommand):
    help = "Create/update crypto-education achievements for the Goals tab"

    def handle(self, *args, **options):
        created = 0
        updated = 0
        for idx, (
            name,
            description,
            trigger_type,
            trigger_value,
            reward_crystals,
            reward_coins,
            _icon_name,
        ) in enumerate(ACHIEVEMENTS, start=1):
            qs = Achievement.objects.filter(sort_order=idx).order_by("id")
            defaults = {
                "name": name,
                "description": description,
                "trigger_type": trigger_type,
                "trigger_value": trigger_value,
                "reward_crystals": reward_crystals,
                "reward_coins": reward_coins,
                "is_active": True,
            }
            if qs.exists():
                ach = qs.first()
                for field, value in defaults.items():
                    setattr(ach, field, value)
                ach.save()
                qs.exclude(pk=ach.pk).update(is_active=False)
                updated += 1
            else:
                Achievement.objects.create(sort_order=idx, **defaults)
                created += 1

        active_ids = Achievement.objects.filter(
            sort_order__gte=1, sort_order__lte=len(ACHIEVEMENTS)
        ).values_list("pk", flat=True)
        Achievement.objects.exclude(pk__in=active_ids).update(is_active=False)

        self.stdout.write(self.style.SUCCESS(f"Achievements seeded: created={created}, updated={updated}"))
