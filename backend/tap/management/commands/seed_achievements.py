class Command(BaseCommand):
    help = "Create/update default achievements inspired by Rupert's Drop app"

    def handle(self, *args, **options):
        created = 0
        updated = 0
        for idx, (name, description, trigger_type, trigger_value, reward_crystals, reward_coins) in enumerate(
            ACHIEVEMENTS, start=1
        ):
            ach, was_created = Achievement.objects.update_or_create(
                name=name,
                defaults={
                    "description": description,
                    "trigger_type": trigger_type,
                    "trigger_value": trigger_value,
                    "reward_crystals": reward_crystals,
                    "reward_coins": reward_coins,
                    "sort_order": idx,
                    "is_active": True,
                },
            )
            if was_created:
                created += 1
            else:
                updated += 1

        self.stdout.write(self.style.SUCCESS(f"Achievements seeded: created={created}, updated={updated}"))
